-- Restaurant POS database schema for Supabase/PostgreSQL.
-- Run this script in Supabase SQL Editor.

create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric(12,2) not null check (price > 0),
  icon text not null default '🍽️',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists menu_items_active_category_idx
  on public.menu_items (is_active, category);


-- Menu change history: one append-only row for every INSERT, UPDATE, or DELETE.
-- Each row stores the menu item snapshot at the time of the change.
create table if not exists public.menu_item_history (
  id bigint generated by default as identity primary key,
  menu_item_id bigint not null,
  operation text not null check (operation in ('INSERT', 'UPDATE', 'DELETE')),
  name text,
  category text,
  price numeric(12,2),
  icon text,
  created_at timestamptz not null default now()
);

create index if not exists menu_item_history_item_idx
  on public.menu_item_history (menu_item_id, created_at desc);

-- Upgrade an older version of menu_item_history if it was already created.
do $
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'menu_item_history'
      and column_name = 'action'
  ) and not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'menu_item_history'
      and column_name = 'operation'
  ) then
    alter table public.menu_item_history rename column action to operation;
  end if;
end $;

alter table public.menu_item_history
  add column if not exists name text,
  add column if not exists category text,
  add column if not exists price numeric(12,2),
  add column if not exists icon text;

alter table public.menu_item_history
  drop column if exists old_price,
  drop column if exists new_price,
  drop column if exists old_is_active,
  drop column if exists new_is_active;


alter table public.menu_item_history enable row level security;

drop policy if exists "menu_item_history_public_read" on public.menu_item_history;
create policy "menu_item_history_public_read"
  on public.menu_item_history for select
  to anon, authenticated
  using (true);

create or replace function public.audit_menu_item_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.menu_item_history (
      menu_item_id, operation, name, category, price, icon
    )
    values (
      new.id, 'INSERT', new.name, new.category, new.price, new.icon
    );
    return new;

  elsif tg_op = 'UPDATE' then
    insert into public.menu_item_history (
      menu_item_id, operation, name, category, price, icon
    )
    values (
      new.id, 'UPDATE', new.name, new.category, new.price, new.icon
    );
    return new;

  elsif tg_op = 'DELETE' then
    insert into public.menu_item_history (
      menu_item_id, operation, name, category, price, icon
    )
    values (
      old.id, 'DELETE', old.name, old.category, old.price, old.icon
    );
    return old;
  end if;

  return null;
end;
$$;

drop trigger if exists menu_items_audit_history on public.menu_items;
create trigger menu_items_audit_history
after insert or update or delete on public.menu_items
for each row execute function public.audit_menu_item_history();

create index if not exists menu_items_active_category_idx
  on public.menu_items (is_active, category);


-- Menu change history keeps a lightweight audit trail for every create/update/delete.
-- Invoice items keep the transaction-time price separately, so old invoices never
-- change when the menu price changes later.
create table if not exists public.menu_item_history (
  id bigint generated by default as identity primary key,
  menu_item_id bigint not null,
  action text not null check (action in ('INSERT', 'UPDATE', 'DELETE')),
  old_price numeric(12,2),
  new_price numeric(12,2),
  old_is_active boolean,
  new_is_active boolean,
  created_at timestamptz not null default now()
);

create index if not exists menu_item_history_item_idx
  on public.menu_item_history (menu_item_id, created_at desc);

alter table public.menu_item_history enable row level security;

drop policy if exists "menu_item_history_public_read" on public.menu_item_history;
create policy "menu_item_history_public_read"
  on public.menu_item_history for select
  to anon, authenticated
  using (true);

create or replace function public.audit_menu_item_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $
begin
  if tg_op = 'INSERT' then
    insert into public.menu_item_history (
      menu_item_id, action, old_price, new_price,
      old_is_active, new_is_active
    )
    values (
      new.id, 'INSERT', null, new.price,
      null, new.is_active
    );
    return new;

  elsif tg_op = 'UPDATE' then
    insert into public.menu_item_history (
      menu_item_id, action, old_price, new_price,
      old_is_active, new_is_active
    )
    values (
      new.id,
      case
        when old.is_active = true and new.is_active = false then 'DELETE'
        else 'UPDATE'
      end,
      old.price,
      new.price,
      old.is_active,
      new.is_active
    );
    return new;

  elsif tg_op = 'DELETE' then
    insert into public.menu_item_history (
      menu_item_id, action, old_price, new_price,
      old_is_active, new_is_active
    )
    values (
      old.id, 'DELETE', old.price, null,
      old.is_active, null
    );
    return old;
  end if;

  return null;
end;
$;

drop trigger if exists menu_items_audit_history on public.menu_items;
create trigger menu_items_audit_history
after insert or update or delete on public.menu_items
for each row execute function public.audit_menu_item_history();


create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists menu_items_set_updated_at on public.menu_items;
create trigger menu_items_set_updated_at
before update on public.menu_items
for each row execute function public.set_updated_at();

